const GEMINI_PART_MAX_LENGTH = 440;

function splitLongGeminiBlock(block) {
  if (block.length <= GEMINI_PART_MAX_LENGTH) return [block];

  return block
    .split(/\n+/)
    .filter(Boolean)
    .flatMap((line) => {
      if (line.length <= GEMINI_PART_MAX_LENGTH) return [line];

      const chunks = [];
      for (let start = 0; start < line.length; start += GEMINI_PART_MAX_LENGTH) {
        chunks.push(line.slice(start, start + GEMINI_PART_MAX_LENGTH));
      }
      return chunks;
    });
}

function buildGeminiPrompts(sections) {
  const units = sections
    .flatMap((section) => section.split(/\n{2,}/))
    .flatMap(splitLongGeminiBlock);
  const parts = [];
  let current = '';

  units.forEach((unit) => {
    const candidate = current ? `${current}\n\n${unit}` : unit;
    if (candidate.length <= GEMINI_PART_MAX_LENGTH) {
      current = candidate;
      return;
    }

    if (current) parts.push(current);
    current = unit;
  });

  if (current) parts.push(current);
  return parts;
}

