const GEMINI_PART_MAX_LENGTH = 440;

function splitLongGeminiBlock(block) {
  if (block.length <= GEMINI_PART_MAX_LENGTH) return [block];

  const sentences = block.match(/[^。！？\n]+[。！？]?|\n/g) ?? [block];
  const chunks = [];
  let current = '';

  sentences.forEach((sentence) => {
    const candidate = `${current}${sentence}`;
    if (candidate.length <= GEMINI_PART_MAX_LENGTH) {
      current = candidate;
      return;
    }

    if (current) chunks.push(current.trim());
    const characters = Array.from(sentence);
    for (let start = 0; start < characters.length; start += GEMINI_PART_MAX_LENGTH) {
      const piece = characters.slice(start, start + GEMINI_PART_MAX_LENGTH).join('').trim();
      if (piece) chunks.push(piece);
    }
    current = '';
  });

  if (current.trim()) chunks.push(current.trim());
  return chunks;
}

function buildGeminiPrompts(sections) {
  const units = sections
    .flatMap((section) => section.split(/\n{2,}/))
    .flatMap(splitLongGeminiBlock);
  const parts = [];
  let current = '';

  units.forEach((unit) => {
    const candidate = current ? `${current}\n\n${unit}` : unit;
    if (candidate.length <= GEMINI_PART_MAX_LENGTH) {
      current = candidate;
      return;
    }

    if (current) parts.push(current);
    current = unit;
  });

  if (current) parts.push(current);
  return parts;
}

